// Regenerates src/lib/instrumentSamples.ts from the sample dirs.
// Usage: node scripts/gen-instrument-samples.mjs <path-to>/web/public/audio
import { readdirSync, writeFileSync } from 'node:fs'

const AUDIO = process.argv[2] // .../web/public/audio
if (!AUDIO) throw new Error('usage: gen-instrument-samples.mjs <audio-dir>')

const INSTRUMENTS = [
  'guitar-acoustic',
  'guitar-electric',
  'guitar-nylon',
  'bass-electric',
  'violin',
  'cello',
]
const NOTE_RE = /^([A-G])(s?)(-?\d)\.mp3$/

const maps = {}
for (const inst of INSTRUMENTS) {
  maps[inst] = {}
  const skipped = []
  for (const f of readdirSync(`${AUDIO}/${inst}`).sort()) {
    const m = NOTE_RE.exec(f)
    if (!m) {
      if (f.endsWith('.mp3')) skipped.push(f)
      continue
    }
    maps[inst][`${m[1]}${m[2] ? '#' : ''}${m[3]}`] = f
  }
  const count = Object.keys(maps[inst]).length
  if (!count) throw new Error(`no samples mapped for ${inst}`)
  console.log(`${inst}: ${count} notes mapped`)
  if (skipped.length) console.warn(`${inst}: skipped ${skipped.join(', ')}`)
}

const body = JSON.stringify(maps, null, 2)
writeFileSync(
  new URL('../src/lib/instrumentSamples.ts', import.meta.url),
  `/**
 * GENERATED by scripts/gen-instrument-samples.mjs — edit the script, not this file.
 * Samples: tonejs-instruments (github.com/nbrosowsky/tonejs-instruments), CC-BY 3.0.
 */
export const SAMPLED_INSTRUMENTS = [
  'guitar-acoustic',
  'guitar-electric',
  'guitar-nylon',
  'bass-electric',
  'violin',
  'cello',
] as const
export type SampledInstrument = (typeof SAMPLED_INSTRUMENTS)[number]
export type InstrumentName = 'piano' | SampledInstrument
export const INSTRUMENT_NAMES: InstrumentName[] = ['piano', ...SAMPLED_INSTRUMENTS]
/** note name -> filename, resolved against \`/audio/<instrument>/\`. */
export const SAMPLE_URLS: Record<SampledInstrument, Record<string, string>> = ${body}
/** GM program numbers (0-based) for MIDI export. */
export const GM_PROGRAM: Record<InstrumentName, number> = {
  piano: 0,
  'guitar-nylon': 24,
  'guitar-acoustic': 25,
  'guitar-electric': 27,
  'bass-electric': 33,
  violin: 40,
  cello: 42,
}
`
)
console.log('wrote src/lib/instrumentSamples.ts')
